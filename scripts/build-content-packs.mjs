#!/usr/bin/env node
/* Builds Checkpoint's encrypted premium content packs — the part of
 * "an unlicensed copy of the app has no paid content" that lives in the
 * build, not the browser. Premium framework registries (soc2,
 * essential8, iso42001, iso27701, dispirap, nistcsf) are kept as
 * plaintext JSON in checkpoint-content/ (source, never shipped — it's
 * outside public/, so Astro's build never copies it into dist/) and
 * AES-256-GCM encrypted here, once per module key, into
 * dist/checkpoint/packs/*.pack.json — small, content-hashed, ciphertext
 * files that are entirely safe to host publicly: without the matching
 * module key (which only ever travels inside a signed activation file —
 * see public/checkpoint/SETUP.md §7a and tools/ISSUANCE.md) a pack
 * decrypts to nothing.
 *
 * Runs as a postbuild step (see package.json), after
 * hash-checkpoint-assets.mjs — the two don't touch any of the same
 * files, order between them doesn't matter.
 *
 * Reads tools/module-keys.json (gitignored, generated by
 * `node tools/issue-entitlement.mjs keygen-modules` — see ISSUANCE.md).
 * A missing module-keys.json is NOT a build failure: it just means this
 * checkout can't produce premium content, which is exactly correct for
 * anyone who clones this repo without Compliance365's private module
 * keys — the shell app + ISO 27001 baseline still builds and runs fine,
 * every premium framework simply stays unavailable until real keys
 * exist. Same "encryption's absence fails safe, not open" principle as
 * the Ed25519 activation scheme.
 *
 * Uses the SAME encryptPack()/sha256Hex() implementation
 * (public/checkpoint/lib.js) the browser's decryptPack() pairs with —
 * one implementation, never two to keep in sync — via Node's WebCrypto
 * (node:crypto's `webcrypto`), not a third-party crypto library.
 */
import { createHash } from 'node:crypto';
import { webcrypto } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import CheckpointLib from '../public/checkpoint/lib.js';

const { encryptPack } = CheckpointLib;

const CONTENT_DIR = join(process.cwd(), 'checkpoint-content');
const MODULE_KEYS_PATH = join(process.cwd(), 'tools', 'module-keys.json');
const PACKS_OUT_DIR = join(process.cwd(), 'dist', 'checkpoint', 'packs');

function shortHash(buf) {
  return createHash('sha256').update(buf).digest('hex').slice(0, 10);
}
function fullHashHex(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

async function main() {
  if (!existsSync(CONTENT_DIR)) {
    console.log('build-content-packs: no checkpoint-content/ directory found — skipping (no premium content to build).');
    return;
  }
  if (!existsSync(MODULE_KEYS_PATH)) {
    console.log('build-content-packs: tools/module-keys.json not found — skipping content pack build.');
    console.log('  Every premium framework will show as unavailable until keys are generated');
    console.log('  (node tools/issue-entitlement.mjs keygen-modules) and this build re-run.');
    return;
  }
  if (!existsSync(join(process.cwd(), 'dist', 'checkpoint'))) {
    console.log('build-content-packs: dist/checkpoint not found — skipping (did `astro build` run first?)');
    return;
  }

  const moduleKeys = JSON.parse(readFileSync(MODULE_KEYS_PATH, 'utf8'));
  const contentFiles = readdirSync(CONTENT_DIR).filter((f) => f.endsWith('.json'));
  if (!contentFiles.length) {
    console.log('build-content-packs: checkpoint-content/ has no *.json source files — nothing to build.');
    return;
  }

  mkdirSync(PACKS_OUT_DIR, { recursive: true });
  const manifest = {};
  let built = 0, skipped = [];

  for (const file of contentFiles) {
    const moduleId = file.replace(/\.json$/, '');
    const key = moduleKeys[moduleId];
    if (!key) {
      skipped.push(moduleId);
      continue;
    }
    const source = JSON.parse(readFileSync(join(CONTENT_DIR, file), 'utf8'));
    const plaintext = { moduleId: source.moduleId, version: source.version, framework: source.framework, guidance: source.guidance || {}, extra: source.extra || {} };
    const pack = await encryptPack(webcrypto.subtle, key, moduleId, source.version || 1, plaintext);
    const packJson = JSON.stringify(pack);
    const packBuf = Buffer.from(packJson, 'utf8');
    const hash = shortHash(packBuf);
    const outFile = moduleId + '.' + hash + '.pack.json';
    writeFileSync(join(PACKS_OUT_DIR, outFile), packJson);
    manifest[moduleId] = { version: source.version || 1, file: outFile, sha256: fullHashHex(packBuf) };
    built++;
  }

  writeFileSync(join(PACKS_OUT_DIR, 'manifest.json'), JSON.stringify(manifest, null, 2));
  console.log('build-content-packs: built ' + built + ' pack(s)' + (skipped.length ? ', skipped ' + skipped.length + ' (no module key on file: ' + skipped.join(', ') + ')' : '') + ', wrote packs/manifest.json');
}

main();
